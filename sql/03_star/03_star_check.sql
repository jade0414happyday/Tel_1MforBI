-- =========================================================
-- SET.2 labels (re-runnable)
-- 設計：一筆 txn 只有一筆 label（cat1/cat2/memo）
-- 若你要一筆 txn 多筆 labels，改主鍵設計（見下方邊界說明）
-- =========================================================
DROP TABLE IF EXISTS sinopac_txn_labels;

CREATE TABLE sinopac_txn_labels (
  txn_id BIGINT UNSIGNED NOT NULL,
  cat1 VARCHAR(50) NULL,
  cat2 VARCHAR(50) NULL,
  memo VARCHAR(255) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (txn_id),
  CONSTRAINT fk_sinopac_txn_labels_txn_id
    FOREIGN KEY (txn_id) REFERENCES SinoPac_raw_a(id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
) ENGINE=InnoDB
  DEFAULT CHARSET=utf8mb4
  COLLATE=utf8mb4_0900_ai_ci;
/*驗收查詢*/
USE tel_bi;

SELECT COUNT(*) AS raw_cnt FROM SinoPac_raw_a;

SELECT COUNT(*) AS label_cnt FROM sinopac_txn_labels;

-- left join 應該不會少 raw 筆數
SELECT
  COUNT(*) AS joined_cnt,
  SUM(l.txn_id IS NULL) AS no_label_cnt
FROM SinoPac_raw_a a
LEFT JOIN sinopac_txn_labels l
  ON l.txn_id = a.id;

